#!/usr/bin/env node
/**
 * Extracts the handful of Material Symbols (Rounded, weight 400) the UI uses
 * into src/components/icons.generated.ts. Material Symbols are Apache-2.0
 * (Google). Only path data for the listed glyphs is copied; the full set is
 * never bundled.   npm run gen:icons
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "node_modules", "@material-symbols", "svg-400", "rounded");

// NekoPak name → Material Symbols name. Outlined by default, "-fill" for the active state.

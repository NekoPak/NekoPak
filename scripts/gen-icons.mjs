const pathOf = (file) => {
  const svg = readFileSync(join(dir, `${file}.svg`), "utf8");
  const m = /<path d="([^"]+)"/.exec(svg);
  if (!m) throw new Error(`no path in ${file}`);
  return m[1];
};

const out = {};
for (const [name, sym] of Object.entries(MAP)) {
  const o = pathOf(sym);
  let f = o;
  try {
    f = pathOf(`${sym}-fill`);
  } catch {
    /* some glyphs have no filled variant */
  }
  out[name] = f === o ? [o] : [o, f];
}

const header = `// GENERATED by scripts/gen-icons.mjs — do not edit.
// Path data from Material Symbols Rounded (weight 400), © Google, Apache License 2.0.
// https://github.com/google/material-design-icons
`;
writeFileSync(
  join(root, "src", "components", "icons.generated.ts"),
  `${header}export const ICONS: Record<string, readonly [string] | readonly [string, string]> = ${JSON.stringify(out)};\n`,
);
console.log(`icons: ${Object.keys(out).length}`);

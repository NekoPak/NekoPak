#!/usr/bin/env node
/**
 * Generates the native desktop UI assets from the same sources the web UI uses,
 * so the two front ends cannot drift apart:
 *
 *   src/components/icons.generated.ts  -> crates/nekopak-desktop/ui/icons/*.svg
 *                                         crates/nekopak-desktop/ui/generated/icons.slint
 *                                         crates/nekopak-desktop/src/generated/icons.rs
 *   src/styles/schemes.css             -> crates/nekopak-desktop/ui/generated/palette.slint
 *                                         crates/nekopak-desktop/src/generated/palettes.rs
 *   src/lib/locales/*.ts               -> crates/nekopak-desktop/locales/{en,zh-TW,ja,ko}.json
 *
 *   node scripts/gen-native-assets.mjs          regenerate
 *   node scripts/gen-native-assets.mjs --check  fail when committed output is stale
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const desktop = join(root, "crates", "nekopak-desktop");
const check = process.argv.includes("--check");
const stale = [];
const expected = new Map();

function emit(path, content) {
  expected.set(path, content);
  if (check) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== content) stale.push(path);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  if (!existsSync(path) || readFileSync(path, "utf8") !== content) writeFileSync(path, content);
}
const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const snake = (name) => name.replaceAll("-", "_");

/* ---------------------------------------------------------------- icons */
{
  const source = readFileSync(join(root, "src", "components", "icons.generated.ts"), "utf8");
  const icons = JSON.parse(source.slice(source.indexOf("= {") + 2).replace(/;\s*$/, ""));
  const svg = (d) =>
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 -960 960 960" width="24" height="24"><path d="${d}"/></svg>\n`;
  const lines = [];
  for (const [name, [outline, filled]] of Object.entries(icons).sort(([a], [b]) => a.localeCompare(b))) {
    const id = kebab(name);
    emit(join(desktop, "ui", "icons", `${id}.svg`), svg(outline));
    lines.push(`    out property <image> ${id}: @image-url("../icons/${id}.svg");`);
    if (filled) {
      emit(join(desktop, "ui", "icons", `${id}-fill.svg`), svg(filled));
      lines.push(`    out property <image> ${id}-fill: @image-url("../icons/${id}-fill.svg");`);
    } else {
      lines.push(`    out property <image> ${id}-fill: @image-url("../icons/${id}.svg");`);
    }
  }
  emit(
    join(desktop, "ui", "generated", "icons.slint"),
    `// GENERATED by scripts/gen-native-assets.mjs — do not edit.
// Material Symbols Rounded (weight 400), © Google, Apache License 2.0.
export global Icons {
${lines.join("\n")}
}
`,
  );
  const names = Object.keys(icons).sort((a, b) => a.localeCompare(b)).map(kebab);
  emit(
    join(desktop, "src", "generated", "icons.rs"),
    `// GENERATED by scripts/gen-native-assets.mjs — do not edit.
use crate::Icons;
use slint::Image;

/// Looks an icon up by its shared name; \`-fill\` selects the filled variant.
pub fn icon(icons: &Icons<'_>, name: &str) -> Image {
    match name {
${names.map((n) => `        "${n}" => icons.get_${snake(n)}(),\n        "${n}-fill" => icons.get_${snake(n)}_fill(),`).join("\n")}
        _ => Image::default(),
    }
}
`,
  );
  if (!check) {
    // Drop icons that are no longer part of the shared set.
    const dir = join(desktop, "ui", "icons");
    for (const file of readdirSync(dir)) if (!expected.has(join(dir, file))) rmSync(join(dir, file));
  }
}

/* ------------------------------------------------------------- palettes */
{
  const css = readFileSync(join(root, "src", "styles", "schemes.css"), "utf8");
  const accents = JSON.parse(
    readFileSync(join(root, "src", "styles", "accents.generated.ts"), "utf8")
      .match(/export const ACCENTS = (\[[\s\S]*?\]) as const/)[1],
  );
  const block = (selector) => {
    const at = css.indexOf(`\n${selector} {`);
    if (at < 0) throw new Error(`palette block not found: ${selector}`);
    const body = css.slice(css.indexOf("{", at) + 1, css.indexOf("}", at));
    const out = {};
    for (const m of body.matchAll(/--([a-z-]+):\s*#([0-9a-fA-F]{6});/g)) out[m[1]] = m[2].toLowerCase();
    return out;
  };
  const baseLight = block(":root");
  const baseDark = block(':root[data-theme="dark"]');
  const names = [];
  const schemes = [];
  for (const accent of accents) {
    const light = accent.id === "mist" ? block(':root:not([data-accent]), :root[data-accent="mist"]') : block(`:root[data-accent="${accent.id}"]`);
    const dark = accent.id === "mist"
      ? block(':root[data-theme="dark"]:not([data-accent]), :root[data-theme="dark"][data-accent="mist"]')
      : block(`:root[data-theme="dark"][data-accent="${accent.id}"]`);
    const l = { ...baseLight, ...light };
    const d = { ...baseDark, ...dark };
    if (!names.length) names.push(...Object.keys(l));
    for (const scheme of [l, d]) {
      const keys = Object.keys(scheme);
      if (keys.length !== names.length || keys.some((k, i) => k !== names[i])) throw new Error(`palette ${accent.id} has a different token set`);
    }
    schemes.push({ accent, light: l, dark: d });
  }
  emit(
    join(desktop, "ui", "generated", "palette.slint"),
    `// GENERATED by scripts/gen-native-assets.mjs from src/styles/schemes.css — do not edit.
export global Pal {
${names.map((n) => `    in property <color> ${n}: #${schemes[0].light[n]};`).join("\n")}
}
`,
  );
  const table = (scheme) => `[${names.map((n) => `0x${scheme[n]}`).join(", ")}]`;
  emit(
    join(desktop, "src", "generated", "palettes.rs"),
    `// GENERATED by scripts/gen-native-assets.mjs from src/styles/schemes.css — do not edit.
// Material color utilities (Apache-2.0), TonalSpot; identical to the web UI palettes.
use slint::Color;

pub struct Accent {
    pub id: &'static str,
    /// Simplified Chinese source label; translated at display time.
    pub label: &'static str,
    pub swatch: u32,
    pub light: [u32; ${names.length}],
    pub dark: [u32; ${names.length}],
}

pub const ACCENTS: [Accent; ${schemes.length}] = [
${schemes
  .map(
    (s) => `    Accent {
        id: "${s.accent.id}",
        label: "${s.accent.label}",
        swatch: 0x${s.accent.light.slice(1)},
        light: ${table(s.light)},
        dark: ${table(s.dark)},
    },`,
  )
  .join("\n")}
];

fn rgb(value: u32) -> Color {
    Color::from_rgb_u8((value >> 16) as u8, (value >> 8) as u8, value as u8)
}

pub fn apply(pal: &crate::Pal<'_>, colors: &[u32; ${names.length}]) {
${names.map((n, i) => `    pal.set_${snake(n)}(rgb(colors[${i}]));`).join("\n")}
}
`,
  );
}

/* -------------------------------------------------------------- locales */
{
  const dir = join(root, "src", "lib", "locales");
  const load = (file) => {
    const text = readFileSync(join(dir, file), "utf8");
    const start = text.indexOf("{", text.indexOf("export const"));
    const literal = text.slice(start, text.lastIndexOf("}") + 1);
    // Locale modules are plain object literals of reviewed product copy.
    return new Function(`"use strict"; return (${literal});`)();
  };
  const catalogs = {
    en: { ...load("en.ts"), ...load("en-extra.ts") },
    "zh-TW": load("zh-tw.ts"),
    ja: load("ja.ts"),
    ko: load("ko.ts"),
  };
  for (const [locale, table] of Object.entries(catalogs)) {
    const sorted = Object.fromEntries(Object.entries(table).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
    emit(join(desktop, "locales", `${locale}.json`), `${JSON.stringify(sorted, null, 0)}\n`);
  }
}

if (check && stale.length) {
  console.error(`Stale native assets (run: node scripts/gen-native-assets.mjs):\n${stale.map((p) => `  ${p}`).join("\n")}`);
  process.exit(1);
}
console.log(`native assets: ${expected.size} files ${check ? "verified" : "generated"}`);

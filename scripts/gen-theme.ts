/**
 * Generates src/styles/schemes.css from seed colours with Google's
 * material-color-utilities (Apache-2.0), TonalSpot variant.
 *   npm run gen:theme
 * The output is plain CSS custom properties; nothing from this script
 * ships at runtime.
 */
import { argbFromHex, Hct, hexFromArgb, MaterialDynamicColors as D, SchemeTonalSpot } from "@material/material-color-utilities";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

export const ACCENTS: { id: string; label: string; seed: string }[] = [
  { id: "mist", label: "雾蓝", seed: "#4a6a9c" },
  { id: "celadon", label: "青瓷", seed: "#3d7d79" },
  { id: "violet", label: "暮紫", seed: "#6a5a94" },
  { id: "pine", label: "松绿", seed: "#4d7a50" },
  { id: "amber", label: "琥珀", seed: "#8f6a2e" },
  { id: "rose", label: "海棠", seed: "#9a4f63" },
];

const ROLES: [string, keyof typeof D][] = [
  ["primary", "primary"], ["on-primary", "onPrimary"],
  ["primary-container", "primaryContainer"], ["on-primary-container", "onPrimaryContainer"],
  ["secondary", "secondary"], ["secondary-container", "secondaryContainer"], ["on-secondary-container", "onSecondaryContainer"],
  ["tertiary-container", "tertiaryContainer"], ["on-tertiary-container", "onTertiaryContainer"],
  ["surface", "surface"], ["surface-dim", "surfaceDim"], ["surface-bright", "surfaceBright"],
  ["surface-lowest", "surfaceContainerLowest"], ["surface-low", "surfaceContainerLow"],
  ["surface-container", "surfaceContainer"], ["surface-high", "surfaceContainerHigh"], ["surface-highest", "surfaceContainerHighest"],
  ["on-surface", "onSurface"], ["on-surface-variant", "onSurfaceVariant"],
  ["outline", "outline"], ["outline-variant", "outlineVariant"],
  ["error", "error"], ["on-error", "onError"], ["error-container", "errorContainer"], ["on-error-container", "onErrorContainer"],
  ["inverse-surface", "inverseSurface"], ["inverse-on-surface", "inverseOnSurface"], ["inverse-primary", "inversePrimary"],
];

function scheme(seed: string, dark: boolean): string {
  const s = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), dark, 0);
  return ROLES.map(([css, role]) => `  --${css}: ${hexFromArgb((D[role] as { getArgb(x: unknown): number }).getArgb(s))};`).join("\n");
}

/** Fixed-hue tonal pairs (status + file-kind tiles), independent of accent. */
const HUES: Record<string, [number, number]> = {
  ok: [145, 40], warn: [70, 48], video: [300, 34], image: [150, 30], audio: [355, 36],
  doc: [255, 34], archive: [65, 40], code: [195, 30], other: [250, 6],
};
function tone(h: number, c: number, t: number): string {
  return hexFromArgb(Hct.from(h, c, t).toInt());
}
function fixed(dark: boolean): string {
  return Object.entries(HUES).map(([k, [h, c]]) => [
    `  --${k}: ${tone(h, c, dark ? 80 : 40)};`,
    `  --${k}-container: ${tone(h, Math.min(c, 24), dark ? 28 : 92)};`,
    `  --on-${k}-container: ${tone(h, c, dark ? 90 : 25)};`,
  ].join("\n")).join("\n");
}

let css = `/* GENERATED by scripts/gen-theme.ts — do not edit. Material color utilities (Apache-2.0), TonalSpot. */\n\n`;
css += `:root {\n  color-scheme: light;\n${fixed(false)}\n}\n`;
css += `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n    color-scheme: dark;\n${fixed(true).replace(/^/gm, "  ")}\n  }\n}\n`;
css += `:root[data-theme="dark"] {\n  color-scheme: dark;\n${fixed(true)}\n}\n\n`;

for (const a of ACCENTS) {
  const def = a.id === "mist";
  const light = def ? `:root:not([data-accent]), :root[data-accent="${a.id}"]` : `:root[data-accent="${a.id}"]`;
  const darkMq = def
    ? `:root:not([data-theme="light"]):not([data-accent]), :root:not([data-theme="light"])[data-accent="${a.id}"]`
    : `:root:not([data-theme="light"])[data-accent="${a.id}"]`;
  const darkForced = def ? `:root[data-theme="dark"]:not([data-accent]), :root[data-theme="dark"][data-accent="${a.id}"]` : `:root[data-theme="dark"][data-accent="${a.id}"]`;
  css += `/* ${a.label} ${a.seed} */\n${light} {\n${scheme(a.seed, false)}\n}\n`;
  css += `@media (prefers-color-scheme: dark) {\n  ${darkMq} {\n${scheme(a.seed, true).replace(/^/gm, "  ")}\n  }\n}\n`;
  css += `${darkForced} {\n${scheme(a.seed, true)}\n}\n\n`;
}

writeFileSync(join(process.cwd(), "src/styles/schemes.css"), css);
writeFileSync(
  join(process.cwd(), "src/styles/accents.generated.ts"),
  `// GENERATED by scripts/gen-theme.ts\nexport const ACCENTS = ${JSON.stringify(ACCENTS.map((a) => ({ ...a, light: tone(Hct.fromInt(argbFromHex(a.seed)).hue, 40, 45) })), null, 2)} as const;\nexport type AccentId = (typeof ACCENTS)[number]["id"];\n`,
);
console.log(`schemes.css: ${ACCENTS.length} accents × light/dark`);
